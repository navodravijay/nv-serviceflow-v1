test('backup imports validate before replacement and require explicit confirmation', async ({ page }) => {
  await page.goto('/')
  await navigate(page, 'Data & backups')
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Download demo backup', exact: true }).click()])
  const backupText = await readFile((await download.path())!, 'utf8')
  expect(JSON.parse(backupText).snapshot.version).toBe(3)
  await navigate(page, 'Customers')
  await page.getByRole('button', { name: 'Add customer', exact: true }).click()
  await page.getByLabel('Customer name', { exact: true }).fill('Fictional temporary profile')
  await page.getByRole('button', { name: 'Add demo customer', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Fictional temporary profile', exact: true })).toBeVisible()
  await navigate(page, 'Data & backups')
  const invalid = JSON.parse(backupText); invalid.snapshot.parts[0].stock++
  await page.locator('#backup-file').setInputFiles({ name: 'invalid-demo.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(invalid)) })
  await expect(page.locator('.backup-feedback[role="alert"]')).toContainText('Backup validation failed')
  await expect(page.getByText('8 jobs · 7 customers', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Replace workspace with backup', exact: true })).toHaveCount(0)
  await page.locator('#backup-file').setInputFiles({ name: 'valid-demo.json', mimeType: 'application/json', buffer: Buffer.from(backupText) })
  await expect(page.getByText('Backup validated', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Replace workspace with backup', exact: true })).toBeDisabled()
  await expect(page.getByText('8 jobs · 7 customers', { exact: true })).toBeVisible()
  await page.getByRole('checkbox', { name: /I understand this replaces/ }).check()
  await page.getByRole('button', { name: 'Replace workspace with backup', exact: true }).click()
  await expect(page.locator('.backup-feedback[role="status"]')).toContainText('Demo backup restored')
  await navigate(page, 'Customers')
  await expect(page.getByRole('heading', { name: 'Fictional temporary profile', exact: true })).toHaveCount(0)
  await expect(page.locator('.customer-card')).toHaveCount(6)
})

